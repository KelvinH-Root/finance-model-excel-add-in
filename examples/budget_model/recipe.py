def norm(xs: list[float]) -> list[float]:
    s = sum(xs)
    out = [round(x / s, 4) for x in xs]
    out[-1] = round(1 - sum(out[:-1]), 4)
    return out


# Seasonality by month of the financial year (April first): maintenance peaks in late spring and
# summer, capital works slow over winter and stop for the Christmas break.
MAINTENANCE = norm([0.085, 0.085, 0.080, 0.079, 0.082, 0.085, 0.088, 0.090, 0.076, 0.072, 0.086, 0.092])
CAPITAL = norm([0.088, 0.084, 0.074, 0.070, 0.077, 0.085, 0.091, 0.094, 0.070, 0.058, 0.099, 0.110])
EVEN = [1 / 12] * 12
PROFILES = [MAINTENANCE, CAPITAL, EVEN]

# Business units: their position in the drop-down (1 is Whole business).
AKL, WKO, CAP = 2, 3, 4


def fy_index(t: int) -> int:
    """0 for FY2026, 1 for FY2027, 2 for FY2028."""
    return t // 12


def fy_month(t: int) -> int:
    return t % 12 + 1


def phased(annual_fy27: float, growth: float, profile: int, t: int, noise: float = 0.0, actual: bool = False) -> float:
    """What a line does in month t: FY2027's annual amount, less a year's growth for FY2026 and plus one for FY2028,
    spread by the profile; actual months carry noise."""
    v = annual_fy27 * (1 + growth) ** (fy_index(t) - 1) * PROFILES[profile - 1][fy_month(t) - 1]
    return r2(v * (1 + rng.uniform(-noise, noise))) if actual else r2(v)


def stepped(base: float, rise: float) -> list[float]:
    return [r2(base * (1 + rise) ** fy_index(t)) for t in range(T)]


