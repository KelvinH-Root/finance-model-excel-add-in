"""The budget demo: a fictional maintenance and construction contractor, as a recipe the engine builds.

    python -m examples.budget_model.recipe      # writes library/hfg/recipes/budget_model.json

Everything here is fictional demo data, shaped like a contractor's budget against actuals: three
business units (Auckland and Waikato maintenance, capital works), revenue and direct costs by GL
code spread by seasonality profiles, salaries and overheads by GL code, the approved budget saved
and a reforecast saved each month, and next year's budget being built. Its history (April 2025 to
September 2026) is generated by running the model's own logic over what "happened", with noise,
from the opening balance sheet at 31 March 2025.
"""

