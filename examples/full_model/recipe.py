"""The full financial model demo: a fictional property services company, as a recipe the engine builds.

    python -m examples.full_model.recipe        # writes library/hfg/recipes/full_model.json

Everything here is fictional demo data. The business: property management fees, maintenance
services priced per job, and project management fees, with the staff, costs, assets, debt and
equity a company like that carries. Its history (April 2025 to September 2026) is generated by
running the model's own logic over the drivers that "happened", with noise, from the opening
balance sheet at 31 March 2025; the model then forecasts October 2026 to March 2028.
"""

