SEED = 20261007
rng = random.Random(SEED)


def cal_month(t: int) -> int:
    return ((START[1] - 1 + t) % 12) + 1


def fy_index(t: int) -> int:
    """0 for FY2026, 1 for FY2027, 2 for FY2028."""
    return t // 12


def noisy(x: float, pct: float) -> float:
    return x * (1 + rng.uniform(-pct, pct))


def r2(x: float) -> float:
    return round(x, 2)


def stepped(base: float, rise: float) -> list[float]:
    """A value that rises by `rise` each April."""
    return [r2(base * (1 + rise) ** fy_index(t)) for t in range(T)]


def growing(base: float, monthly: float) -> list[float]:
    return [r2(base * (1 + monthly) ** t) for t in range(T)]


